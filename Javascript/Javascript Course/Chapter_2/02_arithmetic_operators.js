 // Arithmetic Operators
let a = 5;
let b = 2;
let x = 3;
let y = 8;

console.log("a + b = ", a+b)
console.log("a - b = ", a-b)
console.log("a * b = ", a*b)
console.log("a / b = ", a/b)
console.log("a % b = ", a%b)  // using modulus
console.log("a ** b = ", a**b)  // using exponentation


// UNARY OPERATORS	
console.log("a = ", a++);  // post(later) increment operator
console.log("b = ", b--);  // post decrement opretor
console.log("x = ", ++x);  // pre(before) increment operator
console.log("y = ", --y);  // pre decrement opretor